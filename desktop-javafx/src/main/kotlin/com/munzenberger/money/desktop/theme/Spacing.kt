package com.munzenberger.money.desktop.theme

/** The spacing scale for padding and gaps between nodes. */
object Spacing {
    const val SMALL = 8.0
    const val MEDIUM = 16.0
    const val LARGE = 24.0

    /** Padding around the edge of a screen's content. */
    const val SCREEN_PADDING = MEDIUM

    /** Gap between nodes in a row or column of controls. */
    const val CONTROL_SPACING = SMALL
}
